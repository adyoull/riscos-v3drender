#include <stdio.h>
#include "v3d.h"
#include "v3d_regs.h"
#define P(n, v) printf ("\"%s\": %u,\n", n, (unsigned) (v))
int
main (void)
{
  printf ("{\n");
  P ("HUB_IDENT0", V3D_HUB_IDENT0); P ("HUB_IDENT1", V3D_HUB_IDENT1);
  P ("HUB_IDENT2", V3D_HUB_IDENT2); P ("HUB_IDENT3", V3D_HUB_IDENT3);
  P ("HUB_INT_STS", V3D_HUB_INT_STS); P ("HUB_INT_CLR", V3D_HUB_INT_CLR);
  P ("MMU_DEBUG_INFO", V3D_MMU_DEBUG_INFO); P ("MMU_CTL", V3D_MMU_CTL);
  P ("MMU_PT_PA_BASE", V3D_MMU_PT_PA_BASE); P ("MMUC_CONTROL", V3D_MMUC_CONTROL);
  P ("MMUC_FLUSHING", V3D_MMUC_CONTROL_FLUSHING); P ("TLB_CLEARING", V3D_MMU_CTL_TLB_CLEARING);
  P ("CTL_IDENT0", V3D_CTL_IDENT0); P ("CTL_INT_STS", V3D_CTL_INT_STS);
  P ("CTL_INT_CLR", V3D_CTL_INT_CLR); P ("CTL_INT_MSK_STS", V3D_CTL_INT_MSK_STS);
  P ("CTL_INT_MSK_SET", V3D_CTL_INT_MSK_SET); P ("CTL_INT_MSK_CLR", V3D_CTL_INT_MSK_CLR);
  P ("L2TCACTL", V3D_CTL_L2TCACTL); P ("L2T_BUSY", V3D_L2TCACTL_TMUWCF | V3D_L2TCACTL_L2TFLS);
  P ("CT0QBA", V3D_CLE_CT0QBA); P ("CT0CA", V3D_CLE_CT0CA); P ("CT0QEA", V3D_CLE_CT0QEA);
  P ("CT1QBA", V3D_CLE_CT1QBA); P ("CT1QEA", V3D_CLE_CT1QEA);
  P ("INT_FLDONE", V3D_INT_FLDONE); P ("INT_FRDONE", V3D_INT_FRDONE);
  P ("IOCTL_GET_PARAM", DRM_IOCTL_V3D_GET_PARAM); P ("IOCTL_CREATE_BO", DRM_IOCTL_V3D_CREATE_BO);
  P ("IOCTL_MMAP_BO", DRM_IOCTL_V3D_MMAP_BO); P ("IOCTL_SUBMIT_CL", DRM_IOCTL_V3D_SUBMIT_CL);
  P ("IOCTL_WAIT_BO", DRM_IOCTL_V3D_WAIT_BO); P ("IOCTL_GEM_CLOSE", DRM_IOCTL_GEM_CLOSE);
  P ("IOCTL_SYNCOBJ_CREATE", DRM_IOCTL_SYNCOBJ_CREATE); P ("IOCTL_SYNCOBJ_WAIT", DRM_IOCTL_SYNCOBJ_WAIT);
  P ("SIZEOF_SUBMIT_CL", sizeof (struct drm_v3d_submit_cl));
  P ("PARAM_HUB_IDENT1", DRM_V3D_PARAM_V3D_HUB_IDENT1);
  printf ("\"end\": 0\n}\n");
  return 0;
}
